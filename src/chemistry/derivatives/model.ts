/**
 * Zaitsev's rule as the book states it (tr. 116, 124): the halogen (or –OH) leaves together with a
 * hydrogen of the neighbouring carbon of higher degree. Returns the main product and the others;
 * `single` when every neighbour gives the same alkene.
 */
export function zaitsev(e: Elimination) {
  const top = Math.max(...e.options.map((o) => o.degree));
  const main = e.options.find((o) => o.degree === top) ?? e.options[0];
  const names = [...new Set(e.options.map((o) => o.name))];
  const minor = names.filter((n) => n !== main?.name);
  return { main, minor, single: names.length === 1, top };
}

/**
 * A weak acid HA at analytical concentration C (mol/L) with constant Ka: HA ⇌ H⁺ + A⁻ with
 * Ka = Cα²/(1 − α), solved exactly (the root in 0 < α < 1). The water's own H⁺ is neglected, which
 * the result checks: [H⁺] stays above 10⁻⁶ M for every acid and concentration the app offers.
 */
export function weakAcid(Ka: number, C: number) {
  const alpha = (-Ka + Math.sqrt(Ka * Ka + 4 * Ka * C)) / (2 * C);
  const h = alpha * C;
  return { alpha, h, pH: -Math.log10(h) };
}

/** Independent check of `weakAcid`: bisection on Ka·(C − x) − x² = 0 for x = [H⁺]. */
export function weakAcidBisect(Ka: number, C: number): number {
  let lo = 0;
  let hi = C;
  for (let i = 0; i < 200; i++) {
    const x = (lo + hi) / 2;
    if (Ka * (C - x) - x * x > 0) lo = x;
    else hi = x;
  }
  return (lo + hi) / 2;
}

